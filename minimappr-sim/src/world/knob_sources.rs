//! Knob-generated sources: intermittent flock, same-band species pair,
//! speech and claps.

use std::f64::consts::TAU;
use std::path::Path;

use rand_chacha::ChaCha8Rng;

use super::device_planning::{device_centroid_m, select_devices, EmptySelection};
use super::emission_planning::{bird_call_emission, to_pascals_at_1m, GeneratorSeedStream};
use super::{BirdCallRecord, DistractorRecord, EmissionRecord, PlannedDevice, PlannedEmission};
use crate::physics::geometry::{add, Trajectory, Vec3};
use crate::scenario::chaos::IntermittentFlockKnob;
use crate::scenario::sources::DEFAULT_LABEL_CATEGORY;
use crate::scenario::Scenario;
use crate::signals::calls::{edge_ramp_gain, normalize_active_rms, DEFAULT_NOTE_EDGE_RAMP_S};
use crate::signals::distractors::{clap, speech_babble};
use crate::signals::file_source::load_wav_mono_resampled;
use crate::signals::noise::{derive_stream_rng, uniform_in_range};

/// Height of birds generated by knobs when the canopy knob is off.
const UNDERSTOREY_BIRD_HEIGHT_M: f64 = 2.0;
/// Standing adult mouth height for the speech knob.
const SPEAKING_MOUTH_HEIGHT_M: f64 = 1.6;
/// Flock notes glide slightly downward (chickadee-like "fee-bee" falls).
const FLOCK_NOTE_GLIDE_RATIO: f64 = 0.92;

fn knob_bird_height(scenario: &Scenario, rng: &mut ChaCha8Rng) -> f64 {
    match &scenario.chaos.canopy_gps {
        Some(canopy) => uniform_in_range(
            rng,
            canopy.bird_height_range_m[0],
            canopy.bird_height_range_m[1],
        ),
        None => UNDERSTOREY_BIRD_HEIGHT_M,
    }
}

fn random_point_in_disc(center: Vec3, radius: f64, rng: &mut ChaCha8Rng) -> Vec3 {
    let r = radius * uniform_in_range(rng, 0.0, 1.0).sqrt();
    let azimuth = uniform_in_range(rng, 0.0, TAU);
    [
        center[0] + r * azimuth.cos(),
        center[1] + r * azimuth.sin(),
        center[2],
    ]
}

/// One bout: `notes` short whistles separated by note gaps, unit RMS.
fn flock_bout_samples(knob: &IntermittentFlockKnob, fs: f64, rng: &mut ChaCha8Rng) -> Vec<f32> {
    let note_count = uniform_in_range(
        rng,
        knob.notes_per_bout_range[0] as f64,
        knob.notes_per_bout_range[1] as f64 + 1.0,
    )
    .floor() as usize;
    let mut samples = Vec::new();
    for note in 0..note_count.clamp(1, knob.notes_per_bout_range[1].max(1)) {
        let duration = uniform_in_range(
            rng,
            knob.note_duration_range_s[0],
            knob.note_duration_range_s[1],
        );
        let frequency = uniform_in_range(
            rng,
            knob.note_frequency_range_hz[0],
            knob.note_frequency_range_hz[1],
        );
        let length = (duration * fs) as usize;
        let ramp = (DEFAULT_NOTE_EDGE_RAMP_S * fs) as usize;
        let mut phase = 0.0;
        for i in 0..length {
            let glide = 1.0 + (FLOCK_NOTE_GLIDE_RATIO - 1.0) * i as f64 / length.max(1) as f64;
            phase += TAU * frequency * glide / fs;
            samples.push((phase.sin() * edge_ramp_gain(i, length, ramp)) as f32);
        }
        if note + 1 < note_count {
            let gap = uniform_in_range(rng, knob.note_gap_range_s[0], knob.note_gap_range_s[1]);
            samples.extend(std::iter::repeat_n(0.0, (gap * fs) as usize));
        }
    }
    normalize_active_rms(&mut samples);
    samples
}

fn plan_flock(scenario: &Scenario, emissions: &mut Vec<PlannedEmission>) {
    let Some(knob) = &scenario.chaos.intermittent_flock else {
        return;
    };
    let fs = scenario.sample_rate();
    for bird in 0..knob.bird_count {
        let mut rng = derive_stream_rng(scenario.seed, "intermittent_flock", bird as u64);
        let individual_id = format!("flock-{}", bird + 1);
        let mut perch = random_point_in_disc(knob.center_m, knob.perch_radius_m, &mut rng);
        perch[2] = knob_bird_height(scenario, &mut rng);
        let mut time_s = uniform_in_range(&mut rng, 0.0, knob.bout_gap_range_s[1]);
        let mut bout_index = 0;
        while time_s < scenario.duration_s {
            let samples = flock_bout_samples(knob, fs, &mut rng);
            let bout_duration = samples.len() as f64 / fs;
            let record = BirdCallRecord {
                event_id: format!("sim-{individual_id}-bout{:03}", bout_index + 1),
                individual_id: individual_id.clone(),
                species: vec![knob.species.clone()],
                label: knob.species.clone(),
                label_category: DEFAULT_LABEL_CATEGORY.into(),
                generator_kind: "flock_notes".into(),
                level_db_spl_at_1m: knob.level_db_spl_at_1m,
                origin: "intermittent_flock",
            };
            emissions.push(PlannedEmission {
                emission_id: record.event_id.clone(),
                samples_pa_at_1m: to_pascals_at_1m(samples, knob.level_db_spl_at_1m),
                start_time_s: time_s,
                trajectory: Trajectory::stationary(perch),
                emitting_device_index: None,
                record: EmissionRecord::BirdCall(record),
            });
            if uniform_in_range(&mut rng, 0.0, 1.0) < knob.hop_probability {
                let hop = uniform_in_range(
                    &mut rng,
                    knob.hop_distance_range_m[0],
                    knob.hop_distance_range_m[1],
                );
                let azimuth = uniform_in_range(&mut rng, 0.0, TAU);
                perch = add(perch, [hop * azimuth.cos(), hop * azimuth.sin(), 0.0]);
            }
            time_s += bout_duration
                + uniform_in_range(&mut rng, knob.bout_gap_range_s[0], knob.bout_gap_range_s[1]);
            bout_index += 1;
        }
    }
}

fn plan_same_band_pair(
    scenario: &Scenario,
    emissions: &mut Vec<PlannedEmission>,
) -> Result<(), String> {
    let Some(knob) = &scenario.chaos.same_band_pair else {
        return Ok(());
    };
    let mut rng = derive_stream_rng(scenario.seed, "same_band_pair_heights", 0);
    let members = [
        (
            "a",
            &knob.species_a,
            knob.position_a_m,
            knob.level_a_db_spl_at_1m,
            knob.start_s,
            &knob.generator_a,
        ),
        (
            "b",
            &knob.species_b,
            knob.position_b_m,
            knob.level_b_db_spl_at_1m,
            knob.start_s + knob.b_offset_s,
            &knob.generator_b,
        ),
    ];
    for (member_index, (suffix, species, position, level, start, generator)) in
        members.into_iter().enumerate()
    {
        let mut position = position;
        if scenario.chaos.canopy_gps.is_some() {
            position[2] = knob_bird_height(scenario, &mut rng);
        }
        let individual_id = format!("same-band-{suffix}");
        let record = BirdCallRecord {
            event_id: format!("sim-{individual_id}-001"),
            individual_id,
            species: vec![species.clone()],
            label: species.clone(),
            label_category: DEFAULT_LABEL_CATEGORY.into(),
            generator_kind: generator.kind_name().into(),
            level_db_spl_at_1m: level,
            origin: "same_band_pair",
        };
        let seed_stream = GeneratorSeedStream {
            purpose: "same_band_pair",
            index: member_index as u64,
        };
        emissions.push(bird_call_emission(
            seed_stream,
            scenario,
            generator,
            level,
            start,
            Trajectory::stationary(position),
            record,
        )?);
    }
    Ok(())
}

fn plan_speech(
    scenario: &Scenario,
    devices: &[PlannedDevice],
    emissions: &mut Vec<PlannedEmission>,
) -> Result<(), String> {
    let Some(knob) = &scenario.chaos.speech else {
        return Ok(());
    };
    let fs = scenario.sample_rate();
    for (talker, device_index) in
        select_devices(&knob.near_device_ids, scenario, EmptySelection::FirstPhone)?
            .into_iter()
            .enumerate()
    {
        let mut rng = derive_stream_rng(scenario.seed, "speech", talker as u64);
        let device = &devices[device_index];
        let anchor = device.trajectory.position_at(knob.start_s);
        let azimuth = uniform_in_range(&mut rng, 0.0, TAU);
        let position = [
            anchor[0] + knob.distance_from_device_m * azimuth.cos(),
            anchor[1] + knob.distance_from_device_m * azimuth.sin(),
            SPEAKING_MOUTH_HEIGHT_M,
        ];
        let mut samples = match &knob.wav_path {
            Some(path) => {
                load_wav_mono_resampled(&scenario.base_directory.join(Path::new(path)), fs)?
            }
            None => speech_babble(&knob.babble, fs, &mut rng),
        };
        normalize_active_rms(&mut samples);
        emissions.push(PlannedEmission {
            emission_id: format!("speech-{}", talker + 1),
            samples_pa_at_1m: to_pascals_at_1m(samples, knob.level_db_spl_at_1m),
            start_time_s: knob.start_s,
            trajectory: Trajectory::stationary(position),
            emitting_device_index: None,
            record: EmissionRecord::Distractor(DistractorRecord {
                kind: "speech",
                near_device_id: Some(device.device_id.clone()),
                level_db_spl_at_1m: knob.level_db_spl_at_1m,
            }),
        });
    }
    Ok(())
}

fn plan_claps(
    scenario: &Scenario,
    devices: &[PlannedDevice],
    emissions: &mut Vec<PlannedEmission>,
) {
    let Some(knob) = &scenario.chaos.clap else {
        return;
    };
    let position = knob
        .position_m
        .unwrap_or_else(|| device_centroid_m(devices));
    for (clap_index, time_s) in knob.times_s.iter().enumerate() {
        let mut rng = derive_stream_rng(scenario.seed, "clap", clap_index as u64);
        let samples = clap(&knob.clap, scenario.sample_rate(), &mut rng);
        emissions.push(PlannedEmission {
            emission_id: format!("clap-{}", clap_index + 1),
            samples_pa_at_1m: to_pascals_at_1m(samples, knob.level_db_spl_at_1m),
            start_time_s: *time_s,
            trajectory: Trajectory::stationary(position),
            emitting_device_index: None,
            record: EmissionRecord::Distractor(DistractorRecord {
                kind: "clap",
                near_device_id: None,
                level_db_spl_at_1m: knob.level_db_spl_at_1m,
            }),
        });
    }
}

pub(super) fn plan_knob_emissions(
    scenario: &Scenario,
    devices: &[PlannedDevice],
    emissions: &mut Vec<PlannedEmission>,
) -> Result<(), String> {
    plan_flock(scenario, emissions);
    plan_same_band_pair(scenario, emissions)?;
    plan_speech(scenario, devices, emissions)?;
    plan_claps(scenario, devices, emissions);
    Ok(())
}
